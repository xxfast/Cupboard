/** The resolved palette of the chrome currently drawing, Linux dark by default. */
val LocalChromeTokens: ProvidableCompositionLocal<ChromeTokens> =
    staticCompositionLocalOf { LinuxChrome.dark }

/**
 * The tokens as an M3 [ColorScheme], so stock Material components (menus, tabs,
 * ripples) pick up the chrome palette without per-call color plumbing.
 */
fun ChromeTokens.toColorScheme(dark: Boolean): ColorScheme {
    val base: ColorScheme = if (dark) darkColorScheme() else lightColorScheme()

    return base.copy(
        primary = accent,
        onPrimary = accentText,
        secondaryContainer = tonal,
        onSecondaryContainer = tonalText,
        surface = panel,
        background = chrome,
        surfaceVariant = ctrl,
        outline = outline,
        onSurface = text,
        onSurfaceVariant = dim,
    )
}
