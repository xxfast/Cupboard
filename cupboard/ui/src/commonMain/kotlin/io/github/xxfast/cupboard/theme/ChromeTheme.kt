/**
 * One OS chrome palette in one mode, transcribed from design/platform-theme.js
 * (the canonical token table).
 *
 * Every field is non-null: where an OS palette lacks a token, the closest
 * neighbour fills in (tonal=segOn, tonalText=segOnText, outline=border,
 * ctrlB/ctrlBB=border). Gradient tokens (bar, btnGrad, knob) become top/bottom
 * pairs, equal colors where the source is flat.
 */
data class ChromeTokens(
    val barTop: Color,
    val barBottom: Color,
    val barBorder: Color,
    val title: Color,
    val icon: Color,
    val label: Color,
    val hov: Color,
    val hov2: Color,
    val insBg: Color,
    val div: Color,
    val text: Color,
    val subtle: Color,
    val subtle2: Color,
    val ctrl: Color,
    val ctrlText: Color,
    val ctrlHov: Color,
    val ctrlB: Color,
    val ctrlBB: Color,
    val outline: Color,
    val segBg: Color,
    val segOn: Color,
    val segOnText: Color,
    val segOff: Color,
    val track: Color,
    val rowBg: Color,
    val rowHov: Color,
    val badgeOff: Color,
    val badgeOffText: Color,
    val btnTop: Color,
    val btnBottom: Color,
    val knobTop: Color,
    val knobBottom: Color,
    val tonal: Color,
    val tonalText: Color,
    val chrome: Color,
    val panel: Color,
    val border: Color,
    val dim: Color,
    val faint: Color,
    val well: Color,
    val accent: Color,
    val accentText: Color,
)

/** One OS's chrome: both modes plus the palette-independent metrics. */
data class ChromeTheme(
    val dark: ChromeTokens,
    val light: ChromeTokens,
    val winR: Dp,
    val thumbR: Dp,
    val uiLabel: String,
)

